package com.daliypartice;

public class DataTypesDemo {

    public static void main(String[] args) {

        // Primitive data type: stores an integer value
        int age = 22;

        // Primitive data type: stores a decimal value
        double salary = 25000.50;

        // Primitive data type: stores a single character
        char grade = 'A';

        // Primitive data type: stores true or false
        boolean status = true;

        // Wrapper object for int
        Integer number = 100;

        // Predefined reference type
        String name = "Sai";

        // Display the values
        System.out.println("Age: " + age);
        System.out.println("Salary: " + salary);
        System.out.println("Grade: " + grade);
        System.out.println("Status: " + status);
        System.out.println("Wrapper Object: " + number);
        System.out.println("Name: " + name);
    }
}